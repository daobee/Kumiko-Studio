export const DICTS = { zh, en };

export function detectLang() {
  if (typeof navigator === 'undefined') return 'zh';
  return (navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function makeT(lang) {
  return (key, params) => {
    const raw = DICTS[lang]?.[key] ?? DICTS.en[key] ?? DICTS.zh[key] ?? key;
    if (!params) return raw;
    return String(raw).replace(/\{(\w+)\}/g, (_, k) => params[k] ?? '');
  };
}

export const LangContext = React.createContext({ lang: 'zh', setLang: () => {}, t: makeT('zh') });
export const useLang = () => React.useContext(LangContext);
